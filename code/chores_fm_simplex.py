def update_c(x, N, B):

    return np.concatenate([B / x[:N], np.zeros(M + M * N)])

def polytope_dual(N, M, D, B):
    A = list()
    # when using Gurobi, do not include the nonnegative constraints
    for i in range(N):
        D_i_T = np.zeros(shape=(M, N))
        D_i_T[:, i] = - D[i]
        A_i = np.concatenate([D_i_T, np.identity(M)], axis=1)
        A.append(A_i)
    A = np.concatenate(A, axis=0)
    b = np.zeros(shape=(M * N))
    C = np.concatenate([np.zeros(N), np.ones(M)]).reshape(1, -1)
    d = np.array(sum(B)).reshape(1, )

    return A, b, C, d

def standard_form(A, b, C, d):
    r1, c1 = A.shape
    r2, c1 = C.shape
    c2 = r1

    AI = np.concatenate([A, np.identity(r1)], axis=1)
    new_A = np.concatenate([AI, np.concatenate([C, np.zeros(shape=(r2, c2))], axis=1)], axis=0)
    new_b = np.concatenate([b, d], axis=0)

    return new_A, new_b

