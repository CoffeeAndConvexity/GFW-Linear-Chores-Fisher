def find_basic_feasible_solution(A, b, x_feasible=None):
    """
    Finds a basic feasible solution of a polytope defined by Ax <= b.

    Args:
        A (np.array): The matrix of coefficients for the inequality constraints.
        b (np.array): The right-hand side vector for the inequality constraints.
        x_feasible (np.array, optional): An initial feasible solution.
                                        Not strictly necessary for linprog,
                                        but can be used for warm-starting if needed.

    Returns:
        np.array: A basic feasible solution (vertex) of the polytope,
                  or None if no feasible solution exists.
    """
    num_variables = A.shape[1]
    # Create a dummy objective function (e.g., minimize all zeros)
    c = np.zeros(num_variables)

    # Use linprog to find a basic feasible solution
    # The 'highs' method is generally recommended for performance
    result = linprog(c, A_eq=A, b_eq=b, bounds=(0, None))

    if result.success:
        return result.x
    else:
        print("No feasible solution found.")
        return None

def find_x(N, M, D, B, p, tol=1e-6):

    x = cp.Variable(shape=(N, M), name="x")
    objective = cp.Minimize(0)

    constraints = []
    # mpp constraints
    p_D = p / D
    mpp = np.amax(p_D, axis=1)
    for i in range(N):
        for j in range(M):
            if abs(p_D[i][j] - mpp[i]) > tol:
                constraints.append(x[i, j] == 0)
    # budget constraints
    for i in range(N):
        constraints.append(cp.sum(cp.multiply(p, x[i, :])) == B[i])
    # market clearing
    for j in range(M):
        constraints.append(cp.sum(x[:, j]) == 1)

    prob = cp.Problem(objective, constraints)
    prob.solve()

    return x.value

